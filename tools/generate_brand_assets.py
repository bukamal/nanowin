"""Regenerate every Cashir brand asset from one master image.

The whole visual identity -- launcher icons for Windows/Android/iOS/web/
macOS, the in-app mark, the branding lockup and the splash screens -- is
derived from a single square master kept in the repo
(``branding/source/brand.png``). Running this script repaints every
platform's asset from that master, so the mark can never drift between
platforms again, and swapping the branding is a one-file change (drop a
new master in and re-run) instead of hunting down a dozen PNGs.

The master may be either style:

* light "paper" artwork (the old Nano mark): the pale background is keyed
  to transparency for launcher icons so the mark floats on taskbars and
  adaptive-icon backdrops;
* full-bleed dark artwork (the Cashir mark): kept opaque everywhere, with
  rounded corners only on the in-app/Windows tiles so it reads as a tile.

Only Pillow is required; there is no per-platform drawing code to keep in
sync anymore.

Usage::

    python3 tools/generate_brand_assets.py
"""

from __future__ import annotations

import base64
import io
import textwrap
from pathlib import Path

from PIL import Image, ImageChops, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
ASSETS = ROOT / "src" / "assets"
BRANDING = ROOT / "branding"
SOURCE = BRANDING / "source" / "brand.png"
DEFAULT_LOGO_MODULE = ROOT / "src" / "nano_offline" / "core" / "default_brand.py"

ICON_SIZE = 1024
SPLASH_SIZE = 1242
ICO_SIZES = [(16, 16), (24, 24), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)]

# Launcher icons paint over OS-controlled surfaces (Windows taskbar,
# Android adaptive-icon background), so a light master's flat paper
# background would show as a white sticker there. These are shipped with
# the paper keyed to transparency; everything that is expected to be
# opaque (iOS icons, macOS tiles, splash artwork, in-app branding pngs)
# keeps the master as-is. Dark full-bleed masters are kept opaque.
TRANSPARENT_ICONS = ("icon", "icon_android", "icon_web", "icon_windows")


def _master() -> Image.Image:
    if not SOURCE.exists():
        raise SystemExit(f"missing brand master image: {SOURCE}")
    return Image.open(SOURCE).convert("RGBA")


def _transparent_icon(master: Image.Image) -> Image.Image:
    """Key the master's pale background to transparency.

    ``alpha = 255 - min(r, g, b)``: the mark's strokes are strongly
    coloured (min channel far from 255) while paper is near white, and the
    anti-aliased edges land on proportional alpha values, so the logo
    keeps smooth edges on any launcher backdrop.
    """
    img = master.copy()
    r, g, b, _a = img.split()
    paper = ImageChops.darker(ImageChops.darker(r, g), b)
    img.putalpha(paper.point(lambda v: 255 - v))
    return img


def _is_light_master(master: Image.Image) -> bool:
    """True when the four corners are near-white paper (old Nano style)."""
    w, h = master.size
    for x, y in ((2, 2), (w - 3, 2), (2, h - 3), (w - 3, h - 3)):
        r, g, b, _a = master.getpixel((x, y))
        if min(r, g, b) < 200:
            return False
    return True


def _rounded(img: Image.Image, radius_ratio: float = 0.22) -> Image.Image:
    """Round the corners of a square tile (transparent outside the mask)."""
    size = img.size[0]
    mask = Image.new("L", (size, size), 0)
    ImageDraw.Draw(mask).rounded_rectangle(
        (0, 0, size - 1, size - 1), radius=int(size * radius_ratio), fill=255
    )
    out = img.copy()
    out.putalpha(mask)
    return out


def _square(img: Image.Image, size: int) -> Image.Image:
    """Centre-crop to a square (only if the master isn't already one) and
    resize to ``size`` -- keeps a non-square master from ever distorting."""
    w, h = img.size
    if w != h:
        side = min(w, h)
        left = (w - side) // 2
        top = (h - side) // 2
        img = img.crop((left, top, left + side, top + side))
    if img.size != (size, size):
        img = img.resize((size, size), Image.LANCZOS)
    return img


def _write_default_logo_module(master: Image.Image) -> None:
    """Embed a compact 192px copy for the default printed-document logo.

    The DB seeds this data URI only when ``company_logo`` is absent, so new
    installs get the mark on every invoice without any manual setup.
    """
    img = _square(master, 192)
    buf = io.BytesIO()
    img.save(buf, format="PNG", optimize=True)
    b64 = base64.b64encode(buf.getvalue()).decode("ascii")
    body = "\n".join(f'    "{line}"' for line in textwrap.wrap(b64, 100))
    DEFAULT_LOGO_MODULE.write_text(
        '"""Built-in Cashir brand mark used as the default document logo.\n'
        "\n"
        "Generated by ``tools/generate_brand_assets.py`` from the master; do not\n"
        "hand-edit. Seeded into the ``settings`` table only when ``company_logo``\n"
        "is absent, so existing shops that picked their own logo are never\n"
        "overwritten.\n"
        '"""\n'
        "\n"
        "from __future__ import annotations\n"
        "\n"
        "DEFAULT_COMPANY_LOGO = (\n"
        f"{body}\n"
        ")\n"
        'DEFAULT_COMPANY_LOGO = "data:image/png;base64," + DEFAULT_COMPANY_LOGO\n'
        "\n"
        '__all__ = ["DEFAULT_COMPANY_LOGO"]\n',
        encoding="utf-8",
    )


def _save_png(path: Path, img: Image.Image, size: int) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    _square(img, size).save(path)


def main() -> None:
    master = _master()
    light = _is_light_master(master)
    transparent = _transparent_icon(master) if light else master
    in_app = transparent if light else _rounded(transparent)
    ASSETS.mkdir(parents=True, exist_ok=True)
    BRANDING.mkdir(parents=True, exist_ok=True)

    # In-app mark + OS launcher tiles + branding lockup. Launcher tiles get
    # the keyed background, the in-app/branding pngs stay opaque.
    for name in ("icon", "icon_android", "icon_ios", "icon_macos", "icon_web", "icon_windows"):
        if name in ("icon", "icon_windows"):
            art = in_app
        elif name in TRANSPARENT_ICONS:
            art = transparent
        else:
            art = master
        _save_png(ASSETS / f"{name}.png", art, ICON_SIZE)
    for name in ("app_icon", "cashir_app_icon", "logo_primary"):
        _save_png(BRANDING / f"{name}.png", master, ICON_SIZE)

    _write_default_logo_module(master)

    # Windows multi-resolution icon.
    _square(in_app, max(s for s, _ in ICO_SIZES)).save(
        ASSETS / "icon_windows.ico", sizes=ICO_SIZES
    )

    # Splash screens (light + dark share the same artwork).
    for name in (
        "splash", "splash_android", "splash_ios", "splash_web",
        "splash_dark", "splash_dark_android", "splash_dark_ios", "splash_dark_web",
    ):
        _save_png(ASSETS / f"{name}.png", master, SPLASH_SIZE)

    print(f"brand assets regenerated from {SOURCE.relative_to(ROOT)} ({'light' if light else 'dark'} master)")


if __name__ == "__main__":
    main()
